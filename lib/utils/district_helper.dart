  /// Returns Hindi name for a district/city, or cleanly formats if unknown
  static String getHindiName(String district) {
    if (district.trim().isEmpty) return '';
    
    // If already contains Hindi characters, return clean string
    if (RegExp(r'[\u0900-\u097F]').hasMatch(district)) {
      return district.trim();
    }

    final clean = district.toLowerCase().replaceAll(RegExp(r'\s+'), ' ').trim();
    final noSpaces = clean.replaceAll(' ', '');
    
    // Check exact match
    if (_hindiDistricts.containsKey(clean)) {
      return _hindiDistricts[clean]!;
    }
    if (_hindiDistricts.containsKey(noSpaces)) {
      return _hindiDistricts[noSpaces]!;
    }

    // Check partial key match
    for (final entry in _hindiDistricts.entries) {
      if (clean.contains(entry.key) || entry.key.contains(clean) || noSpaces.contains(entry.key.replaceAll(' ', ''))) {
        return entry.value;
      }
    }

    // Return original as fallback
    return district.trim();
  }

  /// Returns Hindi name for market/mandi name
  static String getHindiMarketName(String market, String district) {
    if (market.trim().isEmpty) return '';

    final distHindi = getHindiName(district);
    final marketClean = market
        .replaceAll(RegExp(r'\s*\(F&V\)', caseSensitive: false), '')
        .replaceAll(RegExp(r'\s*\(Grain\)', caseSensitive: false), '')
        .replaceAll(RegExp(r'\s*APMC', caseSensitive: false), '')
        .trim();

    final mHindi = getHindiName(marketClean);

    if (mHindi.isNotEmpty && mHindi != marketClean) {
      return '$mHindi मंडी';
    } else if (distHindi.isNotEmpty && distHindi != district) {
      return '$distHindi मंडी';
    }

    return marketClean.isEmpty ? '$distHindi मंडी' : '$marketClean मंडी';
  }

